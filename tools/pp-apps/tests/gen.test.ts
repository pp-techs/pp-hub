import { describe, expect, it } from "vite-plus/test";
import { generateGo, generateTs } from "../src/gen.ts";
import type { Resolved } from "../src/repo.ts";
import { manifestFor } from "./fixture.ts";

const resolved = (id: string): Resolved => ({
  entry: { id, server: { dir: `apps/server/ext/${id}` }, web: { dir: `packages/ext-${id}` } },
  manifest: manifestFor(id),
  external: false,
  manifestPath: `apps/server/ext/${id}/pp-app.json`,
});

const builtIns = [resolved("kanban"), resolved("checklist")];

describe("generated files", () => {
  it("writes the Go registration list of the built-ins", () => {
    expect(generateGo(builtIns)).toBe(`// Code generated by pp-apps from pp-apps.json; DO NOT EDIT.

package main

import (
\tchecklist "github.com/nhatbui/pp-hub/apps/server/ext/checklist"
\tkanban "github.com/nhatbui/pp-hub/apps/server/ext/kanban"
\t"github.com/nhatbui/pp-hub/apps/server/extsdk"
)

// extensions are the apps compiled into this build: see pp-apps.json.
func extensions() []extsdk.Ext {
\treturn []extsdk.Ext{kanban.New(), checklist.New()}
}
`);
  });

  it("writes the web registry of the built-ins", () => {
    expect(generateTs(builtIns)).toBe(`// Generated by pp-apps from pp-apps.json; do not edit.
import type { ExtManifest } from "@pp-hub/ext-sdk";
import kanbanExt from "@pp-hub/ext-kanban";
import checklistExt from "@pp-hub/ext-checklist";

export const extensions: ExtManifest[] = [kanbanExt, checklistExt];
`);
  });

  it("sorts an external module's import by path, keeping list order in the call", () => {
    const ext = resolved("acme");
    ext.manifest.server.package = "github.com/acme/pp-acme/ext";
    const go = generateGo([...builtIns, ext]);
    expect(go.indexOf('acme "github.com/acme')).toBeLessThan(go.indexOf("checklist"));
    expect(go).toContain("[]extsdk.Ext{kanban.New(), checklist.New(), acme.New()}");
  });
});
