import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { loadConfig, PATHS, readText, resolveAll, type Config, type Resolved } from "./repo.ts";

const GO_SDK = "github.com/nhatbui/pp-hub/apps/server/extsdk";

/** `apps/server/cmd/server/extensions_gen.go`, in gofmt form. */
export function generateGo(exts: Resolved[]): string {
  const imports = [
    ...exts.map((e) => ({
      path: e.manifest.server.package,
      spec: `${e.manifest.id} "${e.manifest.server.package}"`,
    })),
    { path: GO_SDK, spec: `"${GO_SDK}"` },
  ].sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  const calls = exts.map((e) => `${e.manifest.id}.New()`).join(", ");
  return `// Code generated by pp-apps from pp-apps.json; DO NOT EDIT.

package main

import (
${imports.map((i) => `\t${i.spec}`).join("\n")}
)

// extensions are the apps compiled into this build: see pp-apps.json.
func extensions() []extsdk.Ext {
\treturn []extsdk.Ext{${calls}}
}
`;
}

/** `apps/web/src/ext/registry.gen.ts`. */
export function generateTs(exts: Resolved[]): string {
  const imports = exts.map((e) => `import ${e.manifest.id}Ext from "${e.manifest.web.package}";`);
  const list = exts.map((e) => `${e.manifest.id}Ext`).join(", ");
  return `// Generated by pp-apps from pp-apps.json; do not edit.
import type { ExtManifest } from "@pp-hub/ext-sdk";
${imports.join("\n")}

export const extensions: ExtManifest[] = [${list}];
`;
}

function writeIfChanged(root: string, rel: string, text: string): boolean {
  if (readText(root, rel) === text) return false;
  fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
  fs.writeFileSync(path.join(root, rel), text);
  return true;
}

/** Runs gofmt over source; returns it unchanged when gofmt is not installed. */
function gofmt(source: string): string {
  const r = spawnSync("gofmt", [], { input: source, encoding: "utf8" });
  if (r.error) return source;
  if (r.status !== 0) throw new Error(`gofmt rejected the generated Go file:\n${r.stderr}`);
  return r.stdout;
}

/** Copies each in-repo canonical manifest over its web package's copy. Returns the files that changed. */
export function sync(root: string, exts: Resolved[]): string[] {
  const changed: string[] = [];
  for (const e of exts) {
    if (e.external || !e.webCopyPath) continue;
    const text = readText(root, e.manifestPath);
    if (text !== undefined && writeIfChanged(root, e.webCopyPath, text))
      changed.push(e.webCopyPath);
  }
  return changed;
}

/** Resolves the registered extensions or throws every problem found. */
export function resolveOrThrow(root: string, config: Config): Resolved[] {
  const { resolved, problems } = resolveAll(root, config);
  if (problems.length) throw new Error(problems.join("\n"));
  return resolved;
}

/** Writes the generated files and syncs the manifest copies. Returns the repo-relative files changed. */
export function gen(root: string): string[] {
  const exts = resolveOrThrow(root, loadConfig(root));
  const changed = sync(root, exts);
  if (writeIfChanged(root, PATHS.goGen, gofmt(generateGo(exts)))) changed.push(PATHS.goGen);
  if (writeIfChanged(root, PATHS.tsGen, generateTs(exts))) changed.push(PATHS.tsGen);
  return changed;
}
